def cue_sheet(project):
    cues = json.load(open(os.path.join(project.out, "cues.json"), encoding="utf-8"))
    p = os.path.join(project.out, "cue_sheet.csv")
    with open(p, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["global_frame", "timecode", "scene", "local_frame", "type", "tier", "midi_or_pitch", "gain_db"])
        for c in cues:
            s = T.scene_of(c["f"])
            sec = c["f"] / T.FPS
            w.writerow([round(c["f"], 2), f"{int(sec // 60):02d}:{int(sec % 60):02d}:{int(round((sec % 1) * T.FPS)) % T.FPS:02d}", s, round(c["f"] - T.START[s], 2), c["t"], c["tier"], c.get("midi", c.get("pitch", c.get("base", ""))), c.get("gain", "")])
    return p


def analysis_figure(project):
    o = project.out
    mix = wavfile.read(os.path.join(o, "mix.wav"))[1].astype(np.float64)
    sfx = wavfile.read(os.path.join(o, "stems", "sfx.wav"))[1].astype(np.float64)
    mus = wavfile.read(os.path.join(o, "stems", "music.wav"))[1].astype(np.float64)
    fig, ax = plt.subplots(3, 1, figsize=(16, 10), sharex=True, gridspec_kw={"height_ratios": [1, 1.4, 0.8]})
    for v, c, l in ((mix, "k", "mix"), (mus, "tab:purple", "music"), (sfx, "tab:green", "effects")):
        st = MX.short_term(v, 1.0, 0.25)
        ax[0].plot(np.arange(len(st)) * 0.25 + 0.5, st, c, label=l, lw=1.2)
    ax[0].set_ylabel("momentary LUFS (1 s)")
    ax[0].legend(loc="lower right")
    ax[0].set_ylim(-45, -5)
    ax[0].grid(alpha=0.3)
    m = mix.mean(axis=1)
    ax[1].specgram(m, NFFT=2048, Fs=SR, noverlap=1024, cmap="magma", vmin=-130, vmax=-30)
    ax[1].set_ylim(0, 12000)
    ax[1].set_ylabel("Hz")
    t = np.arange(len(m)) / SR
    ax[2].plot(t[::40], m[::40], lw=0.3, c="k")
    ax[2].set_xlabel("s")
    for s, _ in T.SCENES:
        for a in ax:
            a.axvline(T.START[s] / T.FPS, c="w" if a is ax[1] else "r", lw=0.8, alpha=0.7)
        ax[0].text(T.START[s] / T.FPS + 0.2, -7, s, fontsize=8)
    plt.tight_layout()
    p = os.path.join(o, "mix_analysis.png")
    plt.savefig(p, dpi=90)
    plt.close()
    return p


def mux_check(project, final):
    """decode the AAC track from the muxed file and cross-correlate it with the master wav: lag must be 0 samples"""
    p = subprocess.run(["ffmpeg", "-v", "error", "-i", final, "-f", "f32le", "-ac", "2", "-ar", str(SR), "-"], capture_output=True)
    dec = np.frombuffer(p.stdout, np.float32).reshape(-1, 2).astype(np.float64)
    ref = wavfile.read(os.path.join(project.out, "mix.wav"))[1].astype(np.float64)
    n = min(len(dec), len(ref))
    lags = []
    for frac in (0.08, 0.4, 0.7, 0.92):
        s = int(frac * n)
        s = min(s, n - 3 * SR)
        x, y = dec[s : s + 3 * SR, 0], ref[s : s + 3 * SR, 0]
        c = signal.correlate(x, y, mode="full", method="fft")
        lags.append(int(np.argmax(c)) - (len(y) - 1))
    info = json.loads(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration:stream=codec_name,codec_type,start_time", "-of", "json", final], capture_output=True, text=True).stdout)
    meas = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", final, "-af", "ebur128=peak=true", "-f", "null", "-"], capture_output=True, text=True).stderr
    li = [l for l in meas.splitlines() if "I:" in l and "LUFS" in l]
    tp = [l for l in meas.splitlines() if "Peak:" in l]
    res = dict(lag_samples=lags, lag_ok=all(abs(l) <= 48 for l in lags), ffmpeg_lufs=li[-1].strip() if li else "", ffmpeg_peak=tp[-1].strip() if tp else "", streams=info.get("streams"), duration=info["format"]["duration"])
    print("mux check:", json.dumps({k: v for k, v in res.items() if k != "streams"}))
    json.dump(res, open(os.path.join(project.out, "mux_check.json"), "w"), indent=1)
    return res


def qa_markdown(project):
    o = project.out
    r = lambda n: json.load(open(os.path.join(o, n), encoding="utf-8"))
    mixr, q, a = r("mix_report.json"), r("quality_report.json"), r("sync_audit.json")
    ok = sum(1 for x in a if x["ok"])
    L = ["# QA report (generated by cuelab)", "", "## Master", ""]
    L += [f"- integrated loudness {mixr['lufs_integrated']:.1f} LUFS (target {project.cfg['target_lufs']}), loudness range {mixr['lra_lu']:.1f} LU, true peak {mixr['true_peak_db']:.2f} dBTP (ceiling {project.cfg['ceiling_db']})",
          f"- music alone {mixr['lufs_music_only']:.1f} LUFS, effects alone {mixr['lufs_sfx_only']:.1f} LUFS, {mixr['cue_count']} cues"]
    if "phone_lufs_drop_db" in q:
        L.append(f"- phone-speaker simulation loses {q['phone_lufs_drop_db']:.1f} dB; mono sum loses {q['mono_drop_db']:.2f} dB; L/R correlation {q['lr_correlation']:.2f}")
    if "onset_latency_ms" in q:
        L.append(f"- cue to click onset: mean {q['onset_latency_ms']['mean']:.1f} ms, p95 {q['onset_latency_ms']['p95']:.1f} ms, max {q['onset_latency_ms']['max']:.1f} ms (n={q['onset_latency_ms']['n']})")
    if "tier1_over_music_db" in q:
        L.append(f"- focal events over the music bed: median {q['tier1_over_music_db']['median']:+.1f} dB (n={q['tier1_over_music_db']['n']})")
    L.append(f"- unexplained discontinuities: master {len(q['clicks_master'])}, music stem {len(q['clicks_music'])}")
    L += ["", f"## Sync audit: {ok}/{len(a)} checks inside tolerance", "", "| check | visual frame | cue frame | offset (frames) | ms | result |", "|---|---|---|---|---|---|"]
    for x in a:
        v = "" if x["visual"] is None else f"{x['visual']:.1f}"
        c = "" if x["cue"] is None else f"{x['cue']:.1f}"
        of = "" if x["offset_f"] is None else f"{x['offset_f']:+.2f}"
        ms = "" if x["ms"] is None else f"{x['ms']:+.0f}"
        L.append(f"| {x['name']} | {v} | {c} | {of} | {ms} | {'ok' if x['ok'] else 'FAIL'} {x['note'] if x['visual'] is None else ''} |")
    p = os.path.join(o, "QA_REPORT.md")
    open(p, "w", encoding="utf-8").write("\n".join(L) + "\n")
    return p
